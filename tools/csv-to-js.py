#!/usr/bin/env python3
"""Regenerate js/events.js from data/events.csv.

The site embeds the programme as a JS file (rather than fetching the CSV) so
it also works when index.html is opened straight from disk.

Usage: python3 tools/csv-to-js.py
"""
import csv
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rows = []
with open(root / "data" / "events.csv", newline="", encoding="utf-8-sig") as f:
    for i, r in enumerate(csv.DictReader(f)):
        rows.append({
            "id": f"e{i + 1}",
            "day": r["day"].strip(),
            "startDate": r["start_date"].strip(),
            "startTime": r["start_time"].strip(),
            "endDate": r["end_date"].strip(),
            "endTime": r["end_time"].strip(),
            "name": r["event"].strip(),
            "venue": r["venue"].strip(),
            "type": r["type"].strip(),
            "notes": (r.get("notes") or "").strip(),
        })

out = "// Generated by tools/csv-to-js.py from data/events.csv. Do not edit by hand.\n"
out += "window.FURC_EVENTS = " + json.dumps(rows, ensure_ascii=False, indent=1) + ";\n"
(root / "js" / "events.js").write_text(out, encoding="utf-8")
print(f"Wrote {len(rows)} events to js/events.js")
