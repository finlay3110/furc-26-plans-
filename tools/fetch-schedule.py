#!/usr/bin/env python3
"""Regenerate js/events.js from the pretalx schedule export.

Netlify runs this on every deploy (see netlify.toml), so the site always ships
the schedule as it was at deploy time. If the download fails the build fails,
and Netlify keeps the previous deploy live.

Usage: python3 tools/fetch-schedule.py [url-or-local-file]
"""
import json
import sys
import urllib.request
from datetime import datetime, timedelta
from pathlib import Path

URL = "https://events.furcation.org.uk/furcation-2026/schedule/export/schedule.json"


def load(src):
    if src.startswith("http"):
        req = urllib.request.Request(src, headers={"User-Agent": "furcation-planner"})
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.load(r)
    return json.loads(Path(src).read_text(encoding="utf-8"))


def duration(s):
    # pretalx writes "HH:MM", or "D:HH:MM" for very long slots.
    parts = [int(p) for p in s.split(":")]
    d, h, m = ([0] * (3 - len(parts)) + parts)
    return timedelta(days=d, hours=h, minutes=m)


def convert(data):
    conf = data["schedule"]["conference"]
    days, events, colors = [], [], {}
    for t in conf.get("tracks") or []:
        if t.get("color"):
            colors[t["name"]] = t["color"]
    for day in conf["days"]:
        d = datetime.strptime(day["date"], "%Y-%m-%d")
        days.append({"name": d.strftime("%A"), "date": day["date"], "short": d.strftime("%d %b").upper().lstrip("0")})
        for room, talks in day["rooms"].items():
            for t in talks:
                if "setup" in t["title"].lower():
                    continue  # setup slots aren't open to attendees
                # "date" is ISO with the event's own UTC offset, so its wall clock is local time.
                start = datetime.fromisoformat(t["date"]).replace(tzinfo=None)
                end = start + duration(t["duration"])
                events.append({
                    "id": t.get("code") or t.get("guid") or str(t["id"]),
                    "day": days[-1]["name"],
                    "startDate": start.strftime("%Y-%m-%d"),
                    "startTime": start.strftime("%H:%M"),
                    "endDate": end.strftime("%Y-%m-%d"),
                    "endTime": end.strftime("%H:%M"),
                    "name": t["title"].strip(),
                    "venue": t.get("room") or room,
                    "type": t.get("track") or "",
                    "notes": "",
                })
    if not events:
        sys.exit("No events found in the schedule export; refusing to publish an empty planner.")
    days = [d for d in days if any(e["day"] == d["name"] for e in events)]
    return days, events, colors


def main():
    root = Path(__file__).resolve().parent.parent
    days, events, colors = convert(load(sys.argv[1] if len(sys.argv) > 1 else URL))
    out = "// Generated by tools/fetch-schedule.py from the pretalx schedule. Do not edit by hand.\n"
    out += "window.FURC_DAYS = " + json.dumps(days, ensure_ascii=False) + ";\n"
    out += "window.FURC_TRACK_COLORS = " + json.dumps(colors, ensure_ascii=False) + ";\n"
    out += "window.FURC_EVENTS = " + json.dumps(events, ensure_ascii=False, indent=1) + ";\n"
    (root / "js" / "events.js").write_text(out, encoding="utf-8")
    print(f"Wrote {len(events)} events over {len(days)} days to js/events.js")


if __name__ == "__main__":
    main()
